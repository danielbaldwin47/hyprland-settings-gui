# ---------------------------------------------------------------- live values


def read_values(names):
    """One `hyprctl --batch` per page. Returns {name: (value, set_by_user)}."""
    if not names:
        return {}
    cmd = " ; ".join("j/getoption " + n for n in names)
    out = subprocess.run(["hyprctl", "--batch", cmd], capture_output=True, text=True).stdout
    dec, i, vals = json.JSONDecoder(), 0, {}
    while i < len(out):
        while i < len(out) and out[i] in " \n\r\t":
            i += 1
        if i >= len(out):
            break
        obj, i = dec.raw_decode(out, i)
        v = None
        # under hyprlang the complex types all come back as "custom"; under the Lua
        # engine they arrive as "gradient" / "css" / "font_weight" instead.
        for k in ("int", "float", "str", "vec2", "custom", "gradient", "css", "font_weight"):
            if k in obj:
                v = obj[k]
                break
        vals[obj["option"]] = (v, obj.get("set", False))
    return vals


def typed(rec, raw):
    """Coerce a getoption payload into the schema type."""
    t = rec["type"]
    if raw is None:
        return rec["default"]
    if t == "bool":
        return bool(raw)
    if t == "color":
        return "%08x" % (int(raw) & 0xFFFFFFFF) if int(raw) != -1 else "-1"
    if t in ("int",):
        return int(raw)
    if t == "float":
        return float(raw)
    if t == "vec2":
        return list(raw)
    return raw


# ---------------------------------------------------------------- lua emission


def lua_literal(rec, value):
    """Lua does NOT accept the `toString()` text that `descriptions` prints for the
    complex types: a gradient string is parsed as a single colour and a css-gap string
    is rejected outright. Gradient and css-gaps must be emitted as tables
    (HL.Gradient = {colors, angle}, HL.CssGap = {top,right,bottom,left})."""
    t = rec["type"]
    if t == "bool":
        return "true" if value else "false"
    if t in ("int", "float"):
        return repr(value)
    if t == "vec2":
        return "{ %s, %s }" % (value[0], value[1])
    if t == "color":
        return "'0x%s'" % value if value != "-1" else "-1"
    if t == "gradient":
        parts = str(value).split()
        angle = 0
        if parts and parts[-1].endswith("deg"):
            angle = int(float(parts[-1][:-3]))
            parts = parts[:-1]
        colors = ", ".join("'0x%s'" % p for p in parts)
        return "{ colors = { %s }, angle = %d }" % (colors, angle)
    if t == "css_gaps":
        n = [int(float(x)) for x in str(value).split()] or [0]
        while len(n) < 4:
            n.append(n[-1])
        return "{ top = %d, right = %d, bottom = %d, left = %d }" % tuple(n[:4])
    if t == "font_weight":
        return "'%s'" % value
    return "'%s'" % str(value).replace("'", "\\'")


def lua_module(pending):
    """pending: [(rec, value)] -> a hl.config module, the real write path (ADR-0002)."""
    lines = ["-- generated by hyprland-settings-gui (PROTOTYPE)", "hl.config({"]
    for rec, value in pending:
        lines.append("  ['%s'] = %s," % (schema_mod.lua_key(rec["name"]), lua_literal(rec, value)))
    lines += ["})", ""]
    return "\n".join(lines)


def hyprlang_value(rec, value):
    t = rec["type"]
    if t == "bool":
        return "true" if value else "false"
    if t == "vec2":
        return "%s %s" % (value[0], value[1])
    if t == "color":
        return "rgba(%s)" % value if value != "-1" else "-1"
    return str(value)


# ---------------------------------------------------------------- applier


class Applier:
    def __init__(self, mode, out_dir):
        self.mode = mode
        self.out_dir = out_dir
        self.log = []          # [(name, value, mode, ms, note)]
        os.makedirs(out_dir, exist_ok=True)
        self.state = {}        # name -> value, everything written so far

    def apply(self, rec, value):
        t0 = time.perf_counter()
        note = ""
        self.state[rec["name"]] = value
        if self.mode == "keyword":
            r = subprocess.run(["hyprctl", "keyword", rec["name"], hyprlang_value(rec, value)],
                               capture_output=True, text=True)
            note = r.stdout.strip() or r.stderr.strip()
        elif self.mode == "lua":
            recs = [(rec, value)]
            path = os.path.join(self.out_dir, "options.lua")
            tmp = path + ".tmp"
            open(tmp, "w").write(lua_module(list(self._all_pending())))
            os.replace(tmp, path)
            r = subprocess.run(["hyprctl", "reload"], capture_output=True, text=True)
            note = r.stdout.strip()
        else:
            note = lua_module([(rec, value)]).strip().splitlines()[-2]
        ms = (time.perf_counter() - t0) * 1000
        self.log.append((rec["name"], value, self.mode, ms, note))
        return ms, note

    def _all_pending(self):
        return [(RECS_BY_NAME[n], v) for n, v in self.state.items()]


