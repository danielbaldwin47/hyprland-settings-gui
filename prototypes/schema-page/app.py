class Win(Adw.ApplicationWindow):
    def __init__(self, app, sections, applier, curated, show_advanced):
        super().__init__(application=app, title="Hyprland Settings — PROTOTYPE (#8)")
        self.set_default_size(1080, 860)
        self.applier = applier
        self.curated = curated
        self.show_advanced = show_advanced
        self.sections = sections
        self.reset_buttons = []
        self.toast = Adw.ToastOverlay()

        self.switch = Gtk.Switch(valign=Gtk.Align.CENTER, active=curated)
        self.switch.connect("notify::active", lambda *_: self.rebuild())
        box = Gtk.Box(spacing=6)
        box.append(Gtk.Label(label="Curated"))
        box.append(self.switch)
        adv = Gtk.ToggleButton(label="Advanced", active=show_advanced, valign=Gtk.Align.CENTER)
        adv.connect("toggled", lambda b: (setattr(self, "show_advanced", b.get_active()), self.rebuild()))

        self.header = Adw.HeaderBar()
        self.header.pack_end(box)
        self.header.pack_end(adv)
        self.status = Gtk.Label(label="apply mode: %s" % applier.mode)
        self.status.add_css_class("dim-label")
        self.header.pack_start(self.status)

        self.stack = Adw.ViewStack()
        self.sidebar_list = Gtk.ListBox()
        self.sidebar_list.add_css_class("navigation-sidebar")
        self.sidebar_list.connect("row-selected", self.on_section)

        sidebar = Adw.NavigationPage(title="Sections",
                                     child=self._toolbar(Adw.HeaderBar(), Gtk.ScrolledWindow(child=self.sidebar_list)))
        self.content_tv = self._toolbar(self.header, self.stack)
        self.content_page = Adw.NavigationPage(title="Options", child=self.content_tv)
        split = Adw.NavigationSplitView(sidebar=sidebar, content=self.content_page)
        split.set_min_sidebar_width(200)
        self.toast.set_child(split)
        self.set_content(self.toast)
        self.rebuild()

    def _toolbar(self, header, child):
        tv = Adw.ToolbarView()
        tv.add_top_bar(header)
        tv.set_content(child)
        return tv

    def rebuild(self):
        self.curated = self.switch.get_active()
        recs = schema_mod.build(curated=self.curated)
        RECS_BY_NAME.clear()
        RECS_BY_NAME.update({r["name"]: r for r in recs})
        self.reset_buttons = []
        sel = self.sidebar_list.get_selected_row()
        idx = sel.get_index() if sel else 0
        while self.sidebar_list.get_first_child():
            self.sidebar_list.remove(self.sidebar_list.get_first_child())
        self.stack = Adw.ViewStack()
        for s in self.sections:
            page_recs = [r for r in recs if r["section"] == s]
            values = read_values([r["name"] for r in page_recs])
            page = Page(self, s, page_recs, values, self.curated)
            sw = Gtk.ScrolledWindow(child=page)
            self.stack.add_titled(sw, s, s)
            row = Adw.ActionRow(title=s, subtitle="%d options" % len(page_recs))
            self.sidebar_list.append(row)
        self.content_tv.set_content(self.stack)
        rows = [self.sidebar_list.get_row_at_index(i) for i in range(len(self.sections))]
        if rows and rows[idx]:
            self.sidebar_list.select_row(rows[idx])
        self.status.set_label("%s · apply: %s" % ("curated" if self.curated else "RAW (generated only)",
                                                  self.applier.mode))

    def on_section(self, _lb, row):
        if row:
            self.stack.set_visible_child_name(self.sections[row.get_index()])

    def commit(self, rec, value):
        ms, note = self.applier.apply(rec, value)
        t = Adw.Toast.new("%s = %s   (%s, %.0f ms)" % (rec["title"] if self.curated else rec["name"],
                                                       value, self.applier.mode, ms))
        t.set_timeout(2)
        self.toast.add_toast(t)
        print("[apply] %-46s %-24s %6.1f ms  %s" % (rec["name"], value, ms, note), flush=True)
        for r, btn, getter in self.reset_buttons:
            if r["name"] == rec["name"]:
                try:
                    btn.set_visible(getter() != r["default"])
                except Exception:
                    pass


